/**
 * 快递单号的**校验**（v2.78）。
 *
 * ------------------------------------------------------------------ *
 * 为什么只有这三条规则、而不是"让用户逐段核对"
 * ------------------------------------------------------------------ *
 *
 * 用户的诉求是「识别出来以后支持手动改」，但同时问了一句关键的话：
 * 「你觉得在这里用户会想去手动修改一个个检查么？」
 *
 * **答案是"不会"，所以不能要求他逐个看。** 理由：
 *   · 这一步的注意力已经被**切分与归属**占满 —— 那是只有人能做的判断；
 *   · 核对成本高、检出价值低：单号是机器读条码出来的（置信度极高），而人要核对它，
 *     得打开面单放大、逐个比一串 13 位数字 —— **对长数字串做肉眼比对反而会引入新错**；
 *   · 该改的时机在**后果暴露处**（快递数据 Excel 匹配不上、快递信息与面单对不上），不在数据刚出现处。
 *
 * 所以口径是：**系统只把"可疑的"指出来，可疑的才允许就地改**，其余一律只读。
 * 三条规则都只覆盖"确定错了"或"肯定没读到"的情形：
 *
 *   ① **未识别到**（空）—— 条码反光 / 模糊读不出来，最常见的失败，必须人工补；
 *   ② **格式异常** —— 承运商单号是「字母前缀 + 一长串数字」，出现中文、空格、
 *      或**中间混进字母**（条码 OCR 最典型的 `O`/`0`、`I`/`1` 混淆）就一定是读错了；
 *   ③ **与他段重复** —— 一段面单只对应一个单号；两段读出同一个号，必有一处错。
 *
 * **刻意不做的事**：不按"某承运商的精确位数"校验 —— 各家位数本就不统一
 * （演示数据里同时存在 12 位与 13 位），定死位数会误报，误报比漏报更伤这套机制的可信度。
 */

/** 单号状态：`ok` 正常（只读）/ `unread` 未识别到 / `risk` 异常 —— 后两者标出来并可改 */
export type ExpressNoStatus = 'ok' | 'unread' | 'risk'

export interface ExpressNoCheck {
  status: ExpressNoStatus
  /** 异常原因（`risk` / `unread` 时给，一句话，直接显示在界面上） */
  reason?: string
}

/**
 * 宽松格式：最多 3 个字母前缀 + 8~20 位数字。
 *
 * 上限 20 位是为了兜住"读串了、把相邻内容也吞进来"的情况；下限 8 位是各家运单号的最短长度。
 */
const FORMAT = /^[A-Za-z]{0,3}\d{8,20}$/

/**
 * 判定一个单号。
 *
 * @param value  该段的值（`undefined` / 空串 = 没读到）
 * @param others 同批次**其他段**的值（用于查重复）
 */
export function checkExpressNo(value: string | undefined, others: string[] = []): ExpressNoCheck {
  const v = (value ?? '').trim()
  if (!v) return { status: 'unread', reason: '未识别到 —— 面单条码未读出，请手工填写' }
  if (!FORMAT.test(v)) {
    return { status: 'risk', reason: `「${v}」不像有效的快递单号（应为字母前缀 + 一长串数字），疑为条码识别有误` }
  }
  if (others.some((o) => o.trim() === v)) {
    return { status: 'risk', reason: `「${v}」与其他段重复 —— 一段面单只对应一个单号，必有一处读错` }
  }
  return { status: 'ok' }
}
